using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;
using FinitePrizePool.Engine.Core;

namespace FinitePrizePool.Engine.Reports
{
    /// <summary>Writes simulation results as Markdown (the §7.4 simulation report).</summary>
    public static class SimulationReport
    {
        public static string ToMarkdown(IEnumerable<SimulationResult> results, string generatedBy)
        {
            var text = new StringBuilder();
            foreach (var result in results)
            {
                text.Append("## ").Append(result.Mode).Append(' ').Append(Money.Format(result.BetCents))
                    .Append(": ").Append(result.Deals.Count).Append(" complete deal(s)\n\n");
                text.Append("Config `").Append(result.ConfigVersion).Append("`, ").Append(result.TotalSpins.ToString("N0", CultureInfo.InvariantCulture))
                    .Append(" spins in ").Append(result.Elapsed.TotalSeconds.ToString("0.00", CultureInfo.InvariantCulture)).Append(" s.\n\n");

                text.Append("| # | Deal | Spins | Wagers | Payouts | Actual RTP | Prize hits | Longest loss run | Reached 90% exactly |\n");
                text.Append("|---|---|---:|---:|---:|---:|---:|---:|---|\n");
                var n = 1;
                foreach (var deal in result.Deals)
                {
                    text.Append("| ").Append(n++).Append(" | ").Append(deal.DealId).Append(" | ").Append(deal.Spins)
                        .Append(" | ").Append(Money.Format(deal.WagerCents)).Append(" | ").Append(Money.Format(deal.PayoutCents))
                        .Append(" | ").Append(deal.Rtp.Format()).Append(" | ").Append(deal.PrizeHits).Append(" | ").Append(deal.MaxLossRun)
                        .Append(" | ").Append(deal.ReachedTarget ? "yes" : "**no**").Append(" |\n");
                }

                if (result.WindowRtpPercents.Count > 0) AppendWindows(text, result);
                text.Append('\n');
            }
            text.Append("_Generated by ").Append(generatedBy).Append("._\n");
            return text.ToString();
        }

        private static void AppendWindows(StringBuilder text, SimulationResult result)
        {
            var windows = result.WindowRtpPercents;
            var zero = windows.Count(w => w == 0m);
            var atLeastTarget = windows.Count(w => w >= 90m);
            var near = windows.Count(w => w >= 85m && w <= 95m);
            text.Append("\nRTP over each block of ").Append(result.WindowSpins).Append(" consecutive spins (").Append(windows.Count)
                .Append(" blocks): lowest ").Append(Pct(windows.Min())).Append(", highest ").Append(Pct(windows.Max()))
                .Append("; ").Append(zero).Append(" block(s) paid nothing, ").Append(near).Append(" landed within 85-95%, ")
                .Append(atLeastTarget).Append(" paid 90% or more.\n");
        }

        /// <summary>A real-world run: the players, every completed deal, and the deals left unfinished when it stopped.</summary>
        public static string ToMarkdown(RealWorldResult result)
        {
            var s = result.Settings;
            var completed = result.CompletedDeals.ToList();
            var unfinished = result.UnfinishedDeals.ToList();
            var text = new StringBuilder();
            text.Append("## Real-world play: ").Append(result.Players.Count).Append(" players, random modes and bets\n\n");
            text.Append("Config `").Append(result.ConfigVersion).Append("`. ").Append(result.Spins.ToString("N0", CultureInfo.InvariantCulture))
                .Append(" spins in ").Append(result.Sessions).Append(" sessions, ").Append(result.Elapsed.TotalSeconds.ToString("0.00", CultureInfo.InvariantCulture))
                .Append(" s. Stopped: ").Append(result.StopReason).Append(".\n\n");
            text.Append("Settings: modes ").Append(s.IncludeInner && s.IncludeOuter ? "Inner and Outer" : s.IncludeInner ? "Inner" : "Outer")
                .Append(", bets ").Append(Money.Format(s.MinBetCents)).Append("–").Append(Money.Format(s.MaxBetCents))
                .Append(", sessions of ").Append(s.MinSessionSpins).Append("–").Append(s.MaxSessionSpins).Append(" spins, starting balance ")
                .Append(s.StartingBalanceCents > 0 ? Money.Format(s.StartingBalanceCents) : "from the config").Append(".\n\n");

            text.Append("### Players\n\n| Player | Sessions | Spins | Wagered | Won | Player RTP | Biggest win | Balance start → end |\n");
            text.Append("|---|---:|---:|---:|---:|---:|---:|---|\n");
            foreach (var p in result.Players)
            {
                text.Append("| ").Append(p.Name).Append(p.RanOut ? " (ran out)" : "").Append(" | ").Append(p.Sessions).Append(" | ").Append(p.Spins)
                    .Append(" | ").Append(Money.Format(p.WagerCents)).Append(" | ").Append(Money.Format(p.PayoutCents)).Append(" | ").Append(p.Rtp.Format(2))
                    .Append(" | ").Append(Money.Format(p.BiggestWinCents)).Append(" | ").Append(Money.Format(p.StartingBalanceCents))
                    .Append(" → ").Append(Money.Format(p.EndBalanceCents)).Append(" |\n");
            }
            text.Append("\nA player's RTP is not 90%: they play slices of deals that other players also play.\n\n");

            var exact = completed.Count(d => d.ReachedTarget);
            text.Append("### Completed deals: ").Append(completed.Count).Append(", ").Append(exact).Append(" at exactly 90%\n\n");
            AppendDeals(text, completed, result.Players);

            if (unfinished.Count > 0)
            {
                var wager = unfinished.Sum(d => d.WagerCents);
                var payout = unfinished.Sum(d => d.PayoutCents);
                text.Append("\n### Unfinished when the run stopped: ").Append(unfinished.Count).Append(" deals, ")
                    .Append(new Rtp(payout, wager).Format(2)).Append(" RTP so far (not final)\n\n");
                AppendDeals(text, unfinished.OrderByDescending(d => d.Spins).Take(15).ToList(), result.Players);
                if (unfinished.Count > 15) text.Append("\n…and ").Append(unfinished.Count - 15).Append(" more.\n");
            }

            if (result.RejectedSlots.Count > 0)
                text.Append("\nLeft out (deal rejected): ").Append(string.Join("; ", result.RejectedSlots)).Append(".\n");
            return text.ToString();
        }

        private static void AppendDeals(StringBuilder text, IReadOnlyList<SimulatedSlotDeal> deals, IReadOnlyList<SimulatedPlayer> players)
        {
            text.Append("| Deal | Mode/bet | Tickets used | Wagers | Payouts | RTP | Spins by player |\n|---|---|---:|---:|---:|---:|---|\n");
            foreach (var d in deals)
            {
                var byPlayer = string.Join(", ", players.Where(p => d.SpinsByPlayer.ContainsKey(p.Id)).Select(p => p.Name + " " + d.SpinsByPlayer[p.Id]));
                text.Append("| ").Append(d.DealId).Append(" | ").Append(d.Mode).Append(' ').Append(Money.Format(d.BetCents))
                    .Append(" | ").Append(d.Spins.ToString("N0", CultureInfo.InvariantCulture)).Append(" / ").Append(d.TicketCount.ToString("N0", CultureInfo.InvariantCulture))
                    .Append(" | ").Append(Money.Format(d.WagerCents)).Append(" | ").Append(Money.Format(d.PayoutCents))
                    .Append(" | ").Append(d.Rtp.Format(d.Completed ? 4 : 2)).Append(d.Completed && !d.ReachedTarget ? " **not exact**" : "")
                    .Append(" | ").Append(byPlayer).Append(" |\n");
            }
        }

        private static string Pct(decimal value) => value.ToString("0.0", CultureInfo.InvariantCulture) + "%";
    }
}
